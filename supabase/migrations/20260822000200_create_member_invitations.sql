create table if not exists public.cohorts (
  name text primary key check (char_length(trim(name)) between 1 and 50),
  starts_at timestamptz not null,
  created_at timestamptz not null default now()
);

alter table public.cohorts enable row level security;
revoke all on table public.cohorts from anon, authenticated;
grant select on table public.cohorts to authenticated;

create table if not exists public.member_invitations (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(trim(name)) between 2 and 30),
  email text not null check (char_length(trim(email)) between 3 and 320),
  cohort text not null references public.cohorts(name) on update cascade,
  claimed_by uuid unique references auth.users(id) on delete set null,
  claimed_at timestamptz,
  created_at timestamptz not null default now()
);

create unique index if not exists member_invitations_normalized_email_key
  on public.member_invitations (lower(trim(email)));

alter table public.member_invitations enable row level security;
revoke all on table public.member_invitations from anon, authenticated;
revoke all on sequence public.member_invitations_id_seq from anon, authenticated;

