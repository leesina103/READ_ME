import assert from 'node:assert/strict';
import { plan, payment, done, koreanDay, emailBody } from '../supabase/functions/operations-worker/domain.mjs';
import { createWorker } from '../supabase/functions/operations-worker/worker.mjs';
const booking = { id: 'test', name: '테스트', status: 'booked', management_token: 'test-token', updated_at: '2026-11-13T00:00:00Z', interview_slots: { starts_at: '2026-11-15T06:00:00Z' } };
const at = time => Date.parse(time);
const steps = plan(booking, at('2026-11-15T05:00:00Z'));
assert.equal(steps.find(s => s.stage === '30분 전 안내').actionable, true);
assert.match(steps.find(s => s.stage === '30분 전 안내').action, /2:30|14:30|2시 30/);
assert.equal(plan(booking, at('2026-11-15T06:00:00Z')).find(s => s.stage === '30분 전 안내').actionable, false);
assert.equal(plan(booking, at('2026-11-15T06:30:00Z')).find(s => s.stage === '인터뷰 기록').actionable, true);
assert.equal(plan({ ...booking, status: 'cancelled' }, at('2026-11-15T05:00:00Z')).some(s => s.actionable), false);
assert.equal(plan({ ...booking, updated_at: '2026-11-15T05:20:00Z' }, at('2026-11-15T05:20:00Z')).some(s => s.stage === '전날 확인'), false);
const sameDay = plan({ ...booking, updated_at: '2026-11-15T00:00:00Z' }, at('2026-11-15T00:00:00Z'))[0];
assert.equal(sameDay.next, '시작 30분 전 Meet 안내 발송');
assert.doesNotMatch(sameDay.nextDraft, /내일/);
assert.notEqual(plan({ ...booking, updated_at: '2026-11-14T00:00:00Z' }, 0)[0].key, steps[0].key);
assert.equal(koreanDay('2026-11-13T15:00:00Z'), '2026-11-14');
assert.equal(done({ properties: { '상태': { status: { name: '완료' } } } }), true);
assert.equal(done({ archived: true }), true);
const member = { id: 'test', properties: { '회비 납부': { select: { name: '납부' } }, '입금자명': { rich_text: [{ plain_text: '입금자' }] }, '실제 입금액': { number: 50000 }, '입금일': { date: { start: '2026-11-13' } } } };
assert.equal(payment(member).amount, 50000);
assert.equal(payment({ ...member, properties: { ...member.properties, '실제 입금액': { number: null } } }).missing, true);
assert.equal(payment({ ...member, properties: { ...member.properties, '회비 납부': { select: { name: '미납' } } } }), null);
assert.equal(payment(member).key, payment(member).key);
assert.match(emailBody('행동', '초안', '다음', '다음초안', 'url'), /다음 메시지 초안/);
let calls = 0;
const result = await createWorker({}, () => { calls++; throw new Error('요청 금지'); })();
assert.equal(result.status, 'configuration_required');
assert.equal(calls, 0);
console.log('운영 자동화: 시간 경계·취소·변경·입금 검증·설정 전 실행 차단 통과');
